#!/usr/bin/env node
/* eslint-disable */
'use strict';
// ─────────────────────────────────────────────────────────────────────────────
// measure-guard.js — يحجب فخَّي قياسٍ **مقيسَين على هذا الجهاز**، لا مخاوفَ نظرية.
//
// 🔴 العلّة (١): `curl.exe -w` يعيد `code=000` كاذباً — schannel · خروج ٤٣.
//    قِيس 2026-08-31/09-01 بثلاث جلسات مستقلّة: نفسُ الرابط بلا `-w` ⇒ **200**،
//    وبإضافة `-w` وحدها ⇒ **`code=000`** في أقلّ من ثانية. الخادمُ يردّ والأداةُ تكذب.
//    ⚠️ وأخبثُ ما فيه أن الانكسارَ بدا **انتقائياً** (نجا على ردٍّ صغير وانكسر على كبير)
//    فتشكّل نمطٌ **متماسك المعنى** — «الثابتُ حيّ والديناميكيُّ ساقط» — صمد أمام خمسة
//    ضوابطَ معاكسة، وأنتج **بلاغَ عطلِ متجرٍ كاذباً** عاش ساعةً قبل أن ينقضه نظيران.
//    ⇒ الصيغةُ الوحيدة المقبولة لقراءة حالة HTTP هنا: `curl -D -` واقرأ سطرَ الحالة.
//
// 🔴 العلّة (٢): أنبوبٌ يبتلع رمزَ الخروج. `cmd | tail` يعيد رمزَ `tail` لا رمزَ `cmd`
//    ⇒ **بوّابةٌ تُعلَن خضراءَ وهي حمراء**. وقِيس في نفس الليلة وجهُه المعاكس أيضاً:
//    مخرَجٌ فارغ بعد `| tail` قُرئ «تعليقاً» وكان **أنبوباً** — أي أن الأنبوب يكذب في
//    الاتجاهين. ⇒ يُحجب على **أوامر الحكم وحدها** (التي تُنتج نجاحاً/فشلاً)، لا على
//    أوامر القراءة — فالتضييقُ مقصود: حارسٌ واسعٌ يُعطَّل، وحارسٌ ضيّقٌ يُحترَم.
//
// 🟢 وله ضابطٌ معاكس مُثبَت: `node .claude/hooks/measure-guard.js --self-test`
//    يُثبت أنه **يحمرّ** على الانتهاك و**يخضرّ** على الصيغة الصحيحة. وبلا الشقّ الثاني
//    ينقلب الحارسُ سياجاً يمنع الهدفَ الذي كُتب لحمايته.
// ─────────────────────────────────────────────────────────────────────────────
var fs = require('fs');

// أوامرُ **الحكم**: مخرَجُها نجاحٌ أو فشل، ورمزُ خروجها هو النتيجة.
var VERDICT_RE = /\b(npm\s+run|node\s+--check|node\s+worker\/test-routes\.js|gradlew|clasp\s+(push|deploy)|wrangler\s+(deploy|versions|deployments))\b/;
var PIPE_SINK_RE = /\|\s*(tail|head|findstr|grep)\b/;
var PIPEFAIL_RE = /(set\s+-o\s+pipefail|PIPESTATUS)/;

/* 🔴 تُحذَف المناطقُ المقتبَسة قبل أيّ مطابقة — وهذا **إصلاحُ إنذارٍ كاذبٍ وقع فعلاً**:
   أوّلُ استعمالٍ للحارس بعد تركيبه حجب `gh pr create --title "… \`curl -w\` …"` — أي أنه
   منع **توثيقَ نفسه**. والعلاجُ ليس الالتفافَ على الحارس بل تضييقُه: رايةُ `curl` الحقيقية
   **لا تكون داخل اقتباس**، وذكرُها في عنوانٍ أو رسالةٍ أو `echo` يكون داخله دائماً. */
function stripQuoted(s) {
  return String(s)
    .replace(/"(?:[^"\\]|\\.)*"/g, '""')
    .replace(/'(?:[^'\\]|\\.)*'/g, "''");
}

/** يُرجع نصَّ الحجب، أو '' إن كان الأمرُ سليماً. مفصولٌ عن الإدخال ليكون قابلاً للاختبار. */
function verdict(cmd) {
  var c = stripQuoted(cmd || '');
  if (!c) return '';

  // ① `curl` + `-w`/`--write-out` — بأيّ ترتيب، وبأيّ اسمٍ للثنائيّة.
  if (/\bcurl(\.exe)?\b/.test(c) && /(^|\s)(-w\b|--write-out\b)/.test(c)) {
    return 'BLOCKED: curl -w  ->  USE: curl.exe -s -D - -o /dev/null --max-time 60 "<url>"\n\n' +
      '🚫 حُظر: `curl -w` يعيد `code=000` كاذباً على هذا الجهاز (schannel · خروج ٤٣).\n\n' +
      'قِيس بثلاث جلسات مستقلّة: نفسُ الرابط بلا `-w` ⇒ **200**، وبإضافة `-w` وحدها ⇒ `code=000`.\n' +
      'وأنتج هذا الفخُّ بلاغَ «سقوطِ متجر» كاذباً عاش ساعةً في `pending.json`.\n\n' +
      '✅ الصيغة الصحيحة لقراءة الحالة:\n' +
      '     curl.exe -s -D - -o /dev/null --max-time 60 "<الرابط>"   ثمّ اقرأ سطرَ `HTTP/1.1 …`\n' +
      '✅ وللزمن: قِسه **من خارج العملية** (طابعان حول الأمر) لا بـ`%{time_total}`.\n' +
      '⚠️ ورفعُ المهلة جزءٌ من العلاج: الرئيسيةُ البطيئة تحتاج ٦٠ث لا ٣٠.\n' +
      '📖 `_docs/2026-09-01-فخوخ-القياس.md`\n';
  }

  // ② أمرُ حكمٍ يُنبَّب إلى `tail`/`head`/… بلا `pipefail` ⇒ رمزُ الخروج للأنبوب لا للأمر.
  if (VERDICT_RE.test(c) && PIPE_SINK_RE.test(c) && !PIPEFAIL_RE.test(c)) {
    return 'BLOCKED: pipe swallows exit code  ->  USE: set -o pipefail; <cmd> | tail -5\n\n' +
      '🚫 حُظر: أمرُ حكمٍ مُنبَّبٌ إلى `tail`/`head` بلا `pipefail`.\n\n' +
      'رمزُ الخروج يصير رمزَ الأنبوب لا رمزَ الأمر ⇒ **بوّابةٌ تُعلَن خضراءَ وهي حمراء**.\n' +
      'ووجهُه المعاكس مقيسٌ أيضاً: مخرَجٌ فارغ بعد `| tail` يُقرأ «تعليقاً» وهو أنبوب.\n\n' +
      '✅ إمّا:  set -o pipefail; <الأمر> | tail -5\n' +
      '✅ أو:   <الأمر> > out.txt 2>&1; echo "EXIT=$?"; tail -5 out.txt\n' +
      '✅ أو ببساطة: شغّل الأمرَ بلا أنبوب واقرأ مخرَجَه كاملاً.\n' +
      '📖 `_docs/2026-09-01-فخوخ-القياس.md`\n';
  }

  return '';
}

// ── ضابطٌ معاكس مُثبَت: يحمرّ على الانتهاك ويخضرّ على الصيغة الصحيحة ──────────
if (process.argv.indexOf('--self-test') > -1) {
  var CASES = [
    // [الأمر, أيُحجَب؟, الوصف]
    ['curl.exe -s -o /dev/null -w "code=%{http_code}" https://x/', true,
      'الانتهاك المقيس: `-w` مع `-o /dev/null`'],
    ['curl.exe --write-out "%{time_total}" -s https://x/', true,
      '`--write-out` الطويلة تُمسَك أيضاً'],
    ['npm run gate | tail -5', true, 'أمرُ حكمٍ مُنبَّب بلا pipefail'],
    ['node worker/test-routes.js | head -3', true, 'الفحصُ نفسُه مُنبَّب'],
    // ── ضوابطُ الاتجاه المعاكس: بلاها يمرّ حارسٌ يحجب كلَّ شيء «أخضرَ» زوراً ──
    ['curl.exe -s -D - -o /dev/null --max-time 60 https://x/', false,
      'الصيغةُ الصحيحة تمرّ — وإلّا كان الحارسُ سياجاً'],
    ['set -o pipefail; npm run gate | tail -5', false, '`pipefail` يرفع الحجب'],
    ['npm run gate > out.txt 2>&1; echo EXIT=$?', false, 'إعادةُ التوجيه بلا أنبوب تمرّ'],
    ['git log --oneline | head -5', false, 'أمرُ قراءةٍ مُنبَّب لا يُحجَب — التضييقُ مقصود'],
    ['ls -a | tail -3', false, 'قراءةٌ عادية تمرّ'],
    // 🔴 إنذارٌ كاذبٌ وقع فعلاً عند أوّل استعمال: الحارسُ حجب **توثيقَ نفسه**.
    ['echo "curl -w في تعليقٍ عربيّ"', false, '🔴 ذِكرٌ داخل اقتباس يمرّ — الحارسُ لا يحجب توثيقَه'],
    ['gh pr create --title "feat: حارسُ `curl -w`" --body-file x.txt', false,
      '🔴 الحالةُ التي أفشلت الحارسَ أوّلَ مرّة: عنوانُ PR يذكر الراية'],
    ['curl.exe -w "%{http_code}" -s https://x/', true,
      'ضابطٌ مضادّ للتضييق: الرايةُ الحقيقية خارجَ الاقتباس ما زالت تُحجَب']
  ];
  var bad = 0;
  CASES.forEach(function (c) {
    var blocked = verdict(c[0]) !== '';
    var ok = (blocked === c[1]);
    if (!ok) bad++;
    console.log((ok ? '  ✅ ' : '  ❌ ') + c[2] + '  [' + (blocked ? 'محجوب' : 'يمرّ') + ']');
  });
  console.log(bad === 0
    ? 'RESULT: ✅ ' + CASES.length + ' حالة — يحمرّ على الانتهاك ويخضرّ على الصيغة الصحيحة'
    : 'RESULT: ❌ ' + bad + ' فشل');
  process.exit(bad === 0 ? 0 : 1);
}

var input = {};
try { input = JSON.parse(fs.readFileSync(0, 'utf8') || '{}'); } catch (e) { process.exit(0); }
var ti = (input && input.tool_input) || {};
var msg = verdict(ti.command);
if (!msg) process.exit(0);
process.stderr.write(msg);
process.exit(2);
